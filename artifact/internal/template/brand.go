package template

import (
	"fmt"
	"path"
	"regexp"
	"strconv"
	"strings"
)

var hexColor = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)

func typstString(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, "\n", `\n`)
	return `"` + s + `"`
}

func number(v any) string {
	f, ok := v.(float64)
	if !ok {
		return "0"
	}
	return strconv.FormatFloat(f, 'f', -1, 64)
}

// logoFile returns the file name (base name) of a local logo reference that
// is provided as an asset, or "" (a `storage://` or other URL reference is
// resolved by the platform before the call, not by this renderer).
func logoFile(brand map[string]any, assets map[string][]byte) string {
	logo, _ := brand["logo"].(map[string]any)
	ref, _ := logo["ref"].(string)
	if ref == "" || strings.Contains(ref, "://") {
		return ""
	}
	name := path.Clean(ref)
	if _, ok := assets[name]; !ok {
		return ""
	}
	return name
}

// brandTypst generates /brand.typ: the brand (reserved namespace `brand`) as
// typed Typst values, for Typst code (set rules, colors). Texts go through
// the template actions instead.
func brandTypst(brand, doc map[string]any, logo string, po *PrintOptions) (string, error) {
	colors, _ := brand["colors"].(map[string]any)
	fonts, _ := brand["fonts"].(map[string]any)
	page, _ := brand["page"].(map[string]any)
	logoObj, _ := brand["logo"].(map[string]any)
	var b strings.Builder
	b.WriteString("// Generated by the platform: brand (namespace `brand`) as typed Typst values.\n#let brand = (\n  colors: (\n")
	for _, k := range []string{"primary", "secondary", "accent", "text", "muted", "background"} {
		c, _ := colors[k].(string)
		if !hexColor.MatchString(c) {
			return "", fmt.Errorf("invalid color %s: %q", k, c)
		}
		fmt.Fprintf(&b, "    %s: rgb(%s),\n", k, typstString(c))
	}
	b.WriteString("  ),\n  fonts: (\n")
	for _, k := range []string{"heading", "body", "mono"} {
		f, _ := fonts[k].(map[string]any)
		fam, _ := f["family"].(string)
		fmt.Fprintf(&b, "    %s: %s,\n", k, typstString(fam))
	}
	b.WriteString("  ),\n")
	paper := "a4"
	if size, _ := page["size"].(string); size == "Letter" {
		paper = "us-letter"
	}
	m, _ := page["margins_mm"].(map[string]any)
	fmt.Fprintf(&b, "  page: (paper: %q, margins: (top: %smm, right: %smm, bottom: %smm, left: %smm)),\n",
		paper, number(m["top"]), number(m["right"]), number(m["bottom"]), number(m["left"]))
	alt, _ := logoObj["alt"].(string)
	if logo != "" {
		fmt.Fprintf(&b, "  logo: %s,\n", typstString("/"+logo))
	} else {
		b.WriteString("  logo: none,\n")
	}
	fmt.Fprintf(&b, "  logo-alt: %s,\n)\n", typstString(alt))
	locale, _ := doc["locale"].(string)
	if locale == "" {
		locale = "fr"
	}
	fmt.Fprintf(&b, "#let locale = %s\n", typstString(locale))
	// Written only when the print option is given: without it /brand.typ is
	// byte-identical to the one of the versions before the option.
	if po != nil {
		b.WriteString(po.typst())
	}
	return b.String(), nil
}
